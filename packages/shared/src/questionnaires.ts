export type QuestionnaireAnswers = Record<string, number>;

export interface QuestionnaireScoreRow {
  key: string;
  title: string;
  score: number;
  max: number;
  answered: number;
  count: number;
}
export interface QuestionnaireScores {
  answered: number;
  count: number;
  total: number;
  max: number;
  sections: QuestionnaireScoreRow[];
  quadrants: QuestionnaireScoreRow[];
}

export function questionnaireItemCount(def: QuestionnaireDef) {
  return def.sections.reduce((n, sec) => n + sec.items.length, 0);
}

/** جمع نمرات هر حوزه و هر ربع؛ فقط جمع خام (بدون برچسب تشخیصی) */
export function scoreQuestionnaire(def: QuestionnaireDef, answers: QuestionnaireAnswers): QuestionnaireScores {
  const top = Math.max(...def.scale.map((x) => x.value));
  const val = (no: number) => { const v = answers[String(no)]; return typeof v === "number" && v >= 0 && v <= top ? v : null; };
  const row = (key: string, title: string, nos: number[]): QuestionnaireScoreRow => {
    const vals = nos.map(val);
    return { key, title, score: vals.reduce<number>((a, v) => a + (v ?? 0), 0), max: nos.length * top, answered: vals.filter((v) => v !== null).length, count: nos.length };
  };
  const sections = def.sections.map((sec) => row(sec.key, sec.title, sec.items.map((i) => i.no)));
  const quadrants = def.quadrants.map((q) => row(q.key, q.title, q.items));
  const all = def.sections.flatMap((sec) => sec.items.map((i) => i.no));
  const t = row("total", "جمع کل", all);
  return { answered: t.answered, count: t.count, total: t.score, max: t.max, sections, quadrants };
}

/** پاسخ‌ها معتبر و کامل هستند؟ (همه سؤال‌ها با عدد مجاز) */
export function validateAnswers(def: QuestionnaireDef, answers: unknown): { ok: boolean; missing: number[]; clean: QuestionnaireAnswers } {
  const top = Math.max(...def.scale.map((x) => x.value));
  const clean: QuestionnaireAnswers = {};
  const missing: number[] = [];
  const src = (answers && typeof answers === "object" ? answers : {}) as Record<string, unknown>;
  for (const sec of def.sections) for (const it of sec.items) {
    const v = Number(src[String(it.no)]);
    if (Number.isInteger(v) && v >= 0 && v <= top && src[String(it.no)] !== null && src[String(it.no)] !== "") clean[String(it.no)] = v;
    else missing.push(it.no);
  }
  return { ok: missing.length === 0, missing, clean };
}
